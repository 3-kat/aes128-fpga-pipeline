`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// Testbench: tb_KeyExpBlock
//
// PURPOSE:
//   1. Prove KeyExpBlock (4 chained KeyExp1Enc instances) has exactly
//      4-cycle latency: Round Key 1 must NOT be correct at cycle 3,
//      and MUST be correct at cycle 4 - matching RoundEnc's 4-cycle
//      data latency so the two chains stay in sync in the fully
//      pipelined core.
//   2. Chains 10 KeyExpBlock instances back-to-back (exactly the way
//      the pipelined core does: KeyExpBlock1 -> KeyExpBlock2 -> ... ->
//      KeyExpBlock10) to regenerate the *entire* AES-128 key schedule
//      and checks every round key against the FIPS-197 golden vector
//      for Key = 2b7e151628aed2a6abf7158809cf4f3c.
//
// Assumes KeyExpBlock's port list as posted:
//   module KeyExpBlock(
//       input iClk, iReset,
//       input [3:0] iKeyIter, iKeyIterModNk, iKeyIterDivNk,
//       input [32*`Nk-1:0] iNkKeys,
//       output [3:0] oKeyIter, oKeyIterModNk, oKeyIterDivNk,
//       output [32*`Nk-1:0] oNkKeys
//   );
// Reset is active-low. Chaining relies on the fact that each block's
// oKeyIterDivNk auto-increments to the next round's Rcon index once its
// internal ModNk wraps 3->0 - so block N's outputs feed directly into
// block N+1's inputs with no extra glue logic, same as the textbook
// architecture you described (KeyExpBlock1 -> KeyExpBlock2 -> ...).
//////////////////////////////////////////////////////////////////////////////////
`ifndef Nk_DEFINED_TB
`define Nk 4
`define Nk_DEFINED_TB
`endif

module tb_KeyExpBlock;

localparam NR = 10;  // AES-128: Round Keys 1..10 generated beyond the cipher key

reg iClk = 0;
reg iReset = 0;
always #2.5 iClk = ~iClk;  // 200 MHz

// FIPS-197 test key (same one already used for Round Key 1 in tb_RoundsIterEnc)
localparam [127:0] CIPHER_KEY = 128'h2b7e151628aed2a6abf7158809cf4f3c;

// Golden round keys 1..10 (Round Key 0 is just CIPHER_KEY itself, not
// generated by KeyExpBlock - it's the key-whitening key). Plain reg array
// initialized procedurally for maximum tool compatibility (Vivado xsim,
// iverilog, etc. all accept this form; SV '{...} array literals don't
// port cleanly everywhere).
reg [127:0] GOLDEN [1:10];
initial begin
    GOLDEN[1]  = 128'ha0fafe1788542cb123a339392a6c7605;
    GOLDEN[2]  = 128'hf2c295f27a96b9435935807a7359f67f;
    GOLDEN[3]  = 128'h3d80477d4716fe3e1e237e446d7a883b;
    GOLDEN[4]  = 128'hef44a541a8525b7fb671253bdb0bad00;
    GOLDEN[5]  = 128'hd4d1c6f87c839d87caf2b8bc11f915bc;
    GOLDEN[6]  = 128'h6d88a37a110b3efddbf98641ca0093fd;
    GOLDEN[7]  = 128'h4e54f70e5f5fc9f384a64fb24ea6dc4f;
    GOLDEN[8]  = 128'head27321b58dbad2312bf5607f8d292f;
    GOLDEN[9]  = 128'hac7766f319fadc2128d12941575c006e;
    GOLDEN[10] = 128'hd014f9a8c9ee2589e13f0cc8b6630ca6;
end

wire [3:0]   w_iter [0:NR];
wire [3:0]   w_mod  [0:NR];
wire [3:0]   w_div  [0:NR];
wire [127:0] w_keys [0:NR];

assign w_keys[0] = CIPHER_KEY;
assign w_iter[0] = 4'h0;
assign w_mod[0]  = 4'h0;
assign w_div[0]  = 4'h1;      // block 0 computes Round Key 1 -> needs Rcon[1]

genvar g;
generate
    for (g = 0; g < NR; g = g + 1) begin : ROUND
        KeyExpBlock blk (
            .iClk         (iClk),
            .iReset       (iReset),
            .iKeyIter     (w_iter[g]),
            .iKeyIterModNk(w_mod[g]),
            .iNkKeys      (w_keys[g]),
            .iKeyIterDivNk(w_div[g]),
            .oKeyIter     (w_iter[g+1]),
            .oKeyIterModNk(w_mod[g+1]),
            .oNkKeys      (w_keys[g+1]),
            .oKeyIterDivNk(w_div[g+1])
        );
    end
endgenerate

integer pass_cnt = 0;
integer fail_cnt = 0;
task check;
    input [511:0] name;
    input cond;
    begin
        if (cond) begin
            $display("  PASS %0s", name); pass_cnt = pass_cnt + 1;
        end else begin
            $display("  FAIL %0s", name); fail_cnt = fail_cnt + 1;
        end
    end
endtask

integer r;

initial begin
    $dumpfile("tb_KeyExpBlock.vcd");
    $dumpvars(0, tb_KeyExpBlock);
    $display("=========================================");
    $display(" KeyExpBlock - 4-cycle latency + full FIPS-197 key schedule");
    $display("=========================================");

    iReset = 0;
    repeat(3) @(posedge iClk);
    @(negedge iClk);           // release reset off-edge, no race with the DUT's
    iReset = 1;                // own posedge-triggered reset check

    //----------------------------------------------------------------
    // Latency check on the first block: Round Key 1 must land exactly
    // 4 cycles after reset release - not 3, not 5.
    //----------------------------------------------------------------
    @(posedge iClk); #1;  // cycle 1 (keyep0 registers the real cipher key)
    @(posedge iClk); #1;  // cycle 2 (keyep1 registers)
    @(posedge iClk); #1;  // cycle 3 (keyep2 registers)
    check("Round Key 1 NOT yet correct at cycle 3",
          w_keys[1] !== GOLDEN[1]);

    @(posedge iClk); #1;  // cycle 4 (keyep3 registers -> block output valid)
    check("Round Key 1 correct at cycle 4 (confirms 4-cycle latency)",
          w_keys[1] === GOLDEN[1]);

    //----------------------------------------------------------------
    // Let the rest of the 10-block chain settle, then check every
    // round key against FIPS-197. Round key N needs 4*N cycles from
    // reset release; we've used 4 already, so 40 more is comfortable
    // margin for all 10 to be stable.
    //----------------------------------------------------------------
    repeat(40) @(posedge iClk);
    #1;

    $display("\n[Full AES-128 key schedule check]");
    for (r = 1; r <= NR; r = r + 1) begin
        $display("  RK%0d  got=128'h%032H  exp=128'h%032H",
                  r, w_keys[r], GOLDEN[r]);
        if (w_keys[r] === GOLDEN[r]) begin
            $display("  PASS Round Key %0d matches FIPS-197", r);
            pass_cnt = pass_cnt + 1;
        end else begin
            $display("  FAIL Round Key %0d matches FIPS-197", r);
            fail_cnt = fail_cnt + 1;
        end
    end

    $display("\n=========================================");
    $display(" Results: %0d PASSED  %0d FAILED", pass_cnt, fail_cnt);
    $display("=========================================");
    if (fail_cnt == 0) $display(" ALL TESTS PASSED");
    else                $display(" SOME TESTS FAILED");
    $finish;
end

initial begin #150000; $display("WATCHDOG TIMEOUT"); $finish; end

endmodule